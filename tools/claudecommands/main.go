// Command claudecommands reads the slash command table out of a Claude Code
// binary and writes internal/commands/builtin.go, the built-in commands the
// composer offers. Run it after a Claude Code upgrade:
//
//	go run ./tools/claudecommands "$(readlink -f "$(command -v claude)")" > internal/commands/builtin.go
//
// The binary embeds its command definitions as JavaScript object literals
// (name, description, argumentHint, aliases, isHidden). This is a best-effort
// scan; commands whose description is computed at run time come from the
// overrides below.
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"regexp"
	"sort"
	"strings"
)

var (
	commandRE = regexp.MustCompile(`name:"([a-z][a-z0-9-]{1,30})",((?:[^{}]|\{[^{}]*\}){0,700})`)
	descRE    = regexp.MustCompile(`(?:^|[,{])description:"([^"\\]{6,200})"`)
	menuRE    = regexp.MustCompile(`menuDescription:"([^"\\]{6,200})"`)
	getterRE  = regexp.MustCompile(`get description\(\)\{return[^"` + "`" + `]*["` + "`" + `]([^"` + "`" + `$]{6,160})`)
	hintRE    = regexp.MustCompile(`argumentHint:"([^"]{0,80})"`)
	aliasRE   = regexp.MustCompile(`aliases:\[([^\]]*)\]`)
	quotedRE  = regexp.MustCompile(`"([a-z][a-z0-9-]*)"`)
	markerRE  = regexp.MustCompile(`type:"(?:prompt|local|local-jsx)"|argumentHint|supportsNonInteractive|thinClientDispatch|isHidden|aliases|requires:\{|immediate:|menuDescription:|terminalOriented`)
	versionRE = regexp.MustCompile(`/versions/([0-9][0-9.]*)$`)
)

type command struct {
	name, desc, hint string
	aliases          []string
}

// overrides cover commands whose description is computed at run time.
var overrides = map[string]command{
	"diff":   {desc: "View uncommitted changes and per-turn diffs"},
	"exit":   {desc: "Exit Claude Code", aliases: []string{"quit"}},
	"fast":   {desc: "Toggle fast mode", hint: "[on|off]"},
	"init":   {desc: "Initialize a new CLAUDE.md file with codebase documentation"},
	"rewind": {desc: "Restore the code or the conversation to an earlier point", aliases: []string{"checkpoint", "undo"}},
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: claudecommands <path to the claude binary>")
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	found := map[string]command{}
	hidden := map[string]bool{}
	for _, m := range commandRE.FindAllSubmatch(printable(data), -1) {
		name, body := string(m[1]), string(m[2])
		if _, ok := found[name]; ok || hidden[name] || !markerRE.MatchString(body) {
			continue
		}
		if strings.Contains(body, "isHidden:!0") {
			hidden[name] = true
			continue
		}
		c := command{name: name}
		for _, re := range []*regexp.Regexp{descRE, menuRE, getterRE} {
			if d := re.FindStringSubmatch(body); d != nil {
				c.desc = d[1]
				break
			}
		}
		if c.desc == "" {
			continue
		}
		if h := hintRE.FindStringSubmatch(body); h != nil {
			c.hint = h[1]
		}
		if a := aliasRE.FindStringSubmatch(body); a != nil {
			for _, q := range quotedRE.FindAllStringSubmatch(a[1], -1) {
				c.aliases = append(c.aliases, q[1])
			}
		}
		found[name] = c
	}
	for name, c := range overrides {
		c.name = name
		found[name] = c
	}
	if len(found) < 40 {
		log.Fatalf("found only %d commands; the binary's format may have changed", len(found))
	}
	names := make([]string, 0, len(found))
	for n := range found {
		names = append(names, n)
	}
	sort.Strings(names)
	version := "unknown"
	if v := versionRE.FindStringSubmatch(os.Args[1]); v != nil {
		version = v[1]
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go run ./tools/claudecommands; DO NOT EDIT.\n\npackage commands\n\n")
	fmt.Fprintf(&b, "// BuiltinVersion is the Claude Code version the built-in list came from.\nconst BuiltinVersion = %q\n\n", version)
	fmt.Fprintf(&b, "// builtin are Claude Code's own slash commands.\nvar builtin = []Command{\n")
	for _, n := range names {
		c := found[n]
		fmt.Fprintf(&b, "\t{Name: %q, Description: %q, ArgumentHint: %q, Aliases: %#v, Kind: KindBuiltin},\n", n, c.desc, c.hint, c.aliases)
	}
	b.WriteString("}\n")
	fmt.Print(strings.ReplaceAll(b.String(), "[]string(nil)", "nil"))
}

// printable replaces runs of non-printable bytes with newlines, so the
// regular expressions only see the embedded JavaScript text.
func printable(data []byte) []byte {
	out := bytes.Map(func(r rune) rune {
		if r == '\t' || (r >= 0x20 && r < 0x7f) {
			return r
		}
		return '\n'
	}, data)
	return out
}
